import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
import {buildFranchiseCatalog,mergeFranchiseCatalog} from "./franchise_catalog.mjs";
import {initializeFranchiseEstimatedCosts,estimateReferenceSale,COST_ESTIMATE_RATE} from "./franchise_cost_estimates.mjs";
const source=readFileSync("source/pote_app_base.html","utf8");
const matrix=JSON.parse(source.match(/<script id="backup" type="application\/json">([\s\S]*?)<\/script>/)[1]);
const catalog=buildFranchiseCatalog({data:matrix});
const state={data:{recipes:[],ingredients:[],beverages:[],combos:[],brand:{},
 businessType:"batataria",settings:{...matrix.settings}}};
mergeFranchiseCatalog(state,catalog);
const sandbox={window:{},console};vm.createContext(sandbox);
vm.runInContext(readFileSync("beverage_catalog.js","utf8"),sandbox);
sandbox.window.POTE_DRINKS.ensure(state);
assert.equal(COST_ESTIMATE_RATE,0.60);
const result=initializeFranchiseEstimatedCosts(state,matrix);
assert.equal(result.recipesUpdated,26);
assert.equal(result.ingredientsUpdated,41);
assert.equal(result.beveragesUpdated,11);
assert(state.data.ingredients.every(i=>i.purchasePrice>0&&i.costSource==="franchise-estimate-60"));
assert(state.data.recipes.every(r=>r.estimatedSalePrice>0&&
 Math.abs(r.estimatedUnitCost-Math.round(r.estimatedSalePrice*0.6*100)/100)<0.001));
assert(state.data.beverages.every(b=>Math.abs(b.purchasePrice-b.sellPrice*0.60)<0.001));
assert.equal(state.data.recipes.find(r=>r.id==="fr-r01").estimatedSalePrice,20.5);
assert.equal(state.data.recipes.find(r=>r.id==="fr-r01").estimatedUnitCost,12.3);
const batata=state.data.ingredients.find(i=>i.id==="fr-batata");
assert.equal(batata.purchaseUnit,"kg");
assert.equal(batata.purchaseQuantity,1);
assert.equal(state.data.purchases?.length||0,0,"Valores estimados não criam compras");
const originalPrice=batata.purchasePrice,firstRecipe=state.data.recipes[0];
assert.equal(initializeFranchiseEstimatedCosts(state,matrix).changed,false,"Repetição não atualiza custo estimado");
assert.equal(batata.purchasePrice,originalPrice);
batata.purchasePrice=8;batata.price=8;batata.costSource="real-purchase";
const refreshed=initializeFranchiseEstimatedCosts(state,matrix);
assert.equal(refreshed.changed,false,"Não sobrescrever compras reais");
assert.equal(batata.purchasePrice,8);
assert.equal(firstRecipe.estimatedUnitCost,12.3);
const empty=initializeFranchiseEstimatedCosts({data:{recipes:[],ingredients:[]}},matrix);
assert.equal(empty.changed,false);
console.log("PASS: 26 receitas, 41 ingredientes estimados e 11 bebidas a 60%; sem inventar compras ou substituir preços reais.");
