'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const calc=fs.readFileSync('pote_calc_quantum_99_fullscreen.html','utf8');
const nav=fs.readFileSync('pote_calc_launcher.js','utf8');
const css=fs.readFileSync('pote_calc_launcher.css','utf8');
const make=fs.readFileSync('make_beta.py','utf8');
const workflow=fs.readFileSync('.github/workflows/deploy.yml','utf8');
for(const required of ['id="fullscreenBtn"','requestFullscreen','exitFullscreen','pote-calc:fullscreen','pote-calc:close','id="rocketBtn"','id="advanced"','id="test99"'])assert(calc.includes(required),required);
const inlineScripts=[...calc.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]).filter(x=>x.trim());
assert(inlineScripts.length>=2,'motor e interface matemáticos embutidos no HTML');
for(const script of inlineScripts)new vm.Script(script);
new vm.Script(nav);
assert(nav.includes("'navdesktop','navmobile','poteFloatNavigation'"));
assert(nav.includes('isAuthenticated()'));
assert(nav.includes('event')===false||nav.includes('MutationObserver'));
assert(nav.includes('e.origin!==location.origin'));
assert(nav.includes('allowfullscreen'));
assert(css.includes('.pote-calc-expanded'));
assert(make.includes('pote_calc_launcher.js'), 'Beta injeta botão Calculadora');
assert(workflow.includes('cp pote_calc_quantum_99_fullscreen.html public/pote_calc_quantum_99_fullscreen.html'));
console.log('PASS: calculadora 99 dígitos, tela cheia, navegação HOME, segurança e deploy');
