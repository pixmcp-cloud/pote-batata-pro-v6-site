const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path");
const root=__dirname;
const read=f=>fs.readFileSync(path.join(root,f),"utf8");
const src=read("source/pote_app_base.html");
const html=read("public/index.html");
const guard=read("exit_guard.js");
const photo=read("recipe_photo.js");
assert(src.includes("window.POTE_ROUTE_BRIDGE")&&src.includes("POTE_EXIT?.afterRender"),"Navigation bridge and hooks");
assert(guard.includes("window.addEventListener(\"popstate\"")&&guard.includes("bridge()?.navigate?.(next)"),"Android history back");
assert(guard.includes("builderPhotoData")&&guard.includes("sessionStorage.setItem"),"User-scoped image draft");
assert(src.includes("openBuilderIngredient()")&&src.includes("completeIngredient?.(newIngredientId)"),"Ingredient roundtrip");
assert(src.includes("id=\"builderImageFile\"")&&src.includes("id=\"builderImagePreview\""),"Photo file input and preview");
assert(src.includes("id=\"builderPhotoData\"")&&src.includes("imageUrl:document.getElementById('builderPhotoData')?.value"),"Photo saved in recipe record");
assert(photo.includes('MAX_DATA_URL_CHARS=110000')&&photo.includes('context.drawImage(photo,sx,sy,side,side,0,0,size,size)'),"Bounded center crop 1:1");
assert(photo.includes('image/webp')&&photo.includes('image/jpeg')&&photo.includes('window.POTE_EXIT?.captureNow?.()'),"Low-cost compression and draft persistence");
assert(html.includes("recipe_photo.js?v=recipe-square-v5-20261117"),"Photo module referenced in live HTML");
assert(fs.existsSync(path.join(root,"public","recipe_photo.js")),"Photo module copied to hosting");
console.log("PASS: Android back navigation, ingredient draft recovery, 1:1 photo upload/edit, CI contract");
