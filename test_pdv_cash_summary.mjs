import assert from "node:assert/strict";
import {summarizePdvReceipts,countCashDifference} from "./pdv_cash_summary.mjs";
import {openCash,registerCashMovement,confirmRecordedPayment,settlePreviousPayment,calculateCash,closeCash} from "./pdv_cash_core.mjs";
const d={orders:[],cashSessions:[],cashMovements:[]};
openCash(d,{id:"turno-01",openingCash:100,operator:"Vendedora",at:"2026-11-17T10:00:00Z"});
const add=(id,method,price,confirmed=false,session="turno-01")=>d.orders.push({id,name:id,qty:1,price,cashSessionId:session,status:"entregue",paymentMethod:method,paymentStatus:confirmed?"Pago em dinheiro":"nao_pago"});
add("cash","Dinheiro",60,true);
add("pix","Pix",85,false);
add("card","Cartão",45,false);
add("pending","Pix",30,false);
confirmRecordedPayment(d,{orderId:"pix",reference:"extrato verificado"});
confirmRecordedPayment(d,{orderId:"card",reference:"operadora verificada"});
let raw=calculateCash(d,"turno-01");
let summary=summarizePdvReceipts(raw);
assert.deepEqual([summary.cash,summary.pix,summary.card,summary.gross,summary.pending],[60,85,45,190,30]);
assert.equal(summary.expectedCash,160,"Only physical cash contributes to drawer");
assert.equal(countCashDifference(raw,160).status,"certo");
assert.equal(countCashDifference(raw,157).status,"falta");
assert.equal(countCashDifference(raw,165).status,"sobra");
registerCashMovement(d,{id:"s",kind:"suprimento",amount:20,reason:"Troco"});
registerCashMovement(d,{id:"t",kind:"sangria",amount:30,reason:"Retirada banco"});
raw=calculateCash(d,"turno-01");summary=summarizePdvReceipts(raw);
assert.equal(summary.expectedCash,150);
assert.equal(summary.gross,190,"Cash movements are not sale receipts");
closeCash(d,{countedCash:150,at:"2026-11-17T20:00:00Z"});
openCash(d,{id:"turno-02",openingCash:10,operator:"Vendedora",at:"2026-11-18T10:00:00Z"});
settlePreviousPayment(d,{id:"late",orderId:"pending",method:"Pix",reference:"Pix de ontem",at:"2026-11-18T10:05:00Z"});
const lateSummary=summarizePdvReceipts(calculateCash(d,"turno-02"));
assert.equal(lateSummary.pix,30);
assert.equal(lateSummary.gross,30);
assert.equal(lateSummary.expectedCash,10,"Late Pix does not enter physical drawer");
assert.equal(summarizePdvReceipts(calculateCash(d,"turno-01")).gross,190,"Closed report is immutable");
console.log("PASS PDV summary: money, Pix, card, confirmed gross, pending, cash equation, count preview and closed turn.");
