'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const script=fs.readFileSync('premium_motion.js','utf8');
const style=fs.readFileSync('premium_motion.css','utf8');
const build=fs.readFileSync('make_beta.py','utf8');
const workflow=fs.readFileSync('.github/workflows/deploy.yml','utf8');
const pdv=fs.readFileSync('pdv_cash_ui.mjs','utf8');
new vm.Script(script);
assert(script.includes("new MutationObserver"),'Should react to changes in page content');
assert(script.includes("now===lastTitle"),'Should skip reanimation for operations within the same page');
assert(script.includes("prefers-reduced-motion"),'Must honor reduced motion');
assert(style.includes('#page.pote-motion-enter'),'Page entrance animation');
assert(style.includes('#poteFloatDrawer')&&style.includes('#poteFloatNavigation button'),'Premium menu transitions');
assert(style.includes('#poteProfileOverlay:not([hidden])'),'Profile entrance');
assert(style.includes('#potePdvDialog:not([hidden])'),'Cash dialog entrance');
assert(style.includes('@media(prefers-reduced-motion:reduce)'),'Accessibility');
assert(style.includes('#potePdvTrigger:not(.open):after'),'Red when closed');
assert(style.includes('#potePdvTrigger.open'),'Green when open');
assert(pdv.includes('<strong>PDV</strong>'),'PDV button should show PDV label');
assert(pdv.includes('textContent=s?"Aberto":"Fechado"'),'PDV badge follows actual session');
assert(build.includes('premium_motion.js?v=premium-motion-20261117'));
assert(build.includes('pdv_cash_ui.mjs?v=withdrawal-label-20261118'));
assert(workflow.includes('cp premium_motion.css public/premium_motion.css'));
console.log('PASS premium navigation, accessible motion, operational PDV red/green');
