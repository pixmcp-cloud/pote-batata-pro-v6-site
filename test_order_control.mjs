import assert from "node:assert/strict";
import {groupOnlineOrders,duration,STEPS} from "./order_control_core.mjs";
const base={source:"public-checkout",consumerUid:"customer",checkoutId:"c1",orderNumber:12,clientName:"Cliente",name:"Batata",qty:1,createdAt:"2026-11-25T10:00:00Z",deliveryType:"Tele-entrega"};
const a={...base,id:"a",status:"recebido"},b={...base,id:"b",orderNumber:13,status:"recebido"};
const group=(...rows)=>groupOnlineOrders(rows)[0];
assert.deepEqual(group(a,b).ids,["a","b"]);assert.equal(group(a,b).action,"produce");
const prod=o=>({...o,status:"em_producao",stockDeducted:true});
assert.equal(group(prod(a),b).status,"em_preparo");assert.deepEqual(group(prod(a),b).ids,["b"]);
assert.equal(group(prod(a),prod(b)).action,"ready");
const ready=o=>({...prod(o),checkoutReadyAt:"2026-11-25T10:05:00Z"});
assert.equal(group(ready(a),ready(b)).action,"dispatch");
const sent=o=>({...ready(o),checkoutDispatchedAt:"2026-11-25T10:06:00Z"});
assert.equal(group(sent(a),sent(b)).action,"deliver");assert.equal(group(sent(a),sent(b)).status,"saiu_entrega");
assert.equal(group({...ready(a),deliveryType:"Retirada"}).label,"Confirmar retirada");
assert.equal(group(ready(a),{...b,status:"cancelado"}).action,"dispatch");
assert.equal(groupOnlineOrders([{...a,status:"entregue"},{...b,status:"cancelado"}]).length,0);
assert.equal(groupOnlineOrders([{...a,source:"manual"}]).length,0);
assert.equal(duration(base.createdAt,Date.parse("2026-11-25T10:12:05Z")),"00:12:05");assert.equal(duration(null),"--:--:--");assert.equal(STEPS.recebido.color,"#ff4747");
console.log("PASS controle de pedidos online: agrupamento, produção parcial, retirada, despacho e entrega.");
