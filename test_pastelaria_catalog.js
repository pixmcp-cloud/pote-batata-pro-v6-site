const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm");
const ctx={window:{},console,JSON,Map,Set,Math,String,Number,Array,Date};vm.createContext(ctx);
vm.runInContext(fs.readFileSync("universe_templates.js","utf8"),ctx);
vm.runInContext(fs.readFileSync("pastelaria_templates.js","utf8"),ctx);
const s=ctx.window.POTE_UNIVERSE_TEMPLATES.pastelaria;
assert.equal(s.recipes.length,50);
assert.equal(s.recipes.filter(r=>r.category==="Salgados").length,40);
assert.equal(s.recipes.filter(r=>r.category==="Doces").length,10);
assert.equal(new Set(s.recipes.map(r=>r.id)).size,50,"IDs de receitas duplicados");
assert.equal(new Set(s.ingredients.map(r=>r.id)).size,s.ingredients.length,"IDs de ingredientes duplicados");
assert(s.recipes.every(r=>r.imageUrl==="./assets/recipes/pastelaria-cardapio.jpg"),"Foto única obrigatória");
assert(s.recipes.every(r=>r.items.length>=3&&r.steps.length>=5),"Fichas incompletas");
assert(s.recipes.every(r=>r.targetGainPct===100&&r.pricingReady===false));
assert(s.ingredients.every(i=>i.price===0&&i.purchasePrice===0&&i.stock===0),"Sem preços ou estoques fictícios");
const keys=new Set(s.ingredients.map(i=>i.id));
assert(s.recipes.every(r=>r.items.every(i=>keys.has(i.id)&&i.g>0)));
assert(s.recipes.every(r=>r.templateOrigin==="pastelaria"&&r.businessUniverse==="pastelaria"));
assert(fs.readFileSync("source/pote_app_base.html","utf8").includes('custom==="./assets/recipes/pastelaria-cardapio.jpg"'),"Imagem precisa aparecer também no FREE");
assert(fs.readFileSync(".github/workflows/deploy.yml","utf8").includes("cp pastelaria_templates.js public/pastelaria_templates.js"));
assert(fs.existsSync("assets/recipes/pastelaria-cardapio.jpg"),"Imagem da Pastelaria ausente");
console.log("PASS: 40 salgados, 10 doces, ingredientes válidos, imagem única, preço/estoque zerados, FREE visualiza.");
