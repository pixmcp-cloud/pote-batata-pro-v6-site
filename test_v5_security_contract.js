const assert=require("node:assert/strict"),fs=require("node:fs");
const rules=fs.readFileSync("firestore.rules","utf8");
assert(rules.includes("rules_version = '2'"),"Firestore rules_version=2 syntax required");
assert(rules.includes("request.auth.uid == userId"),"Tenant UID isolation required");
assert(rules.includes("request.auth.token.firebase.sign_in_provider == 'google.com'"),"Google provider gate required");
assert(rules.includes("request.auth.token.email_verified == true"),"Verified email gate required");
assert(rules.includes("match /records/{recordId} { allow read, write: if false; }"),"Old V2 records must be denied");
assert(rules.includes("match /appState/{id}")&&rules.includes("id in ['v5','v5Pulse','v5InventoryGuard']"),"Only V5 operational metadata must be readable");
assert(!rules.includes("canWriteLegacy("),"V1 compatibility must be eliminated");
assert(rules.includes("match /recordsV5/{recordId}"),"V5 per-entity record collection required");
assert(rules.includes("allow get, list: if canAccess(userId)"),"V5 reads must enforce tenant isolation");
assert(rules.includes("record.group in"),"V5 must whitelist record groups");
assert(rules.includes("'cashSessions'")&&rules.includes("'cashMovements'"),"PDV records require Firestore rules");
assert(rules.includes("function canUseFinancialRecords(userId)"),"Licenças do caixa devem ser verificadas no servidor");
assert(rules.includes("item.kind in"),"Movimentações financeiras devem validar tipo");
assert(rules.includes("record == oldRecord"),"Movimentações financeiras devem ser imutáveis");
assert(rules.includes("oldItem.status == 'open'"),"Fechamento do caixa deve ser irreversível");
assert(rules.includes("item.get('id', null) == record.id"),"ID financeiro deve coincidir");
assert(rules.includes("document.get('updatedAt', null) == request.time"),"V5 updatedAt must be server-generated");
assert(rules.includes("request.resource.data.diff(resource.data).affectedKeys()"),"Profile updates must limit fields");
assert(rules.includes("allow update, delete: if false"),"Immutable audit events required");
assert(rules.includes("match /{document=**}")&&rules.includes("allow read, write: if false"),"Default deny required");
assert(!/allow\s+(read|write|create|update|delete)\s*:\s*if\s+true\s*;/.test(rules),"Broad access policy forbidden");
const config=fs.readFileSync("gallery_config.mjs","utf8");
assert(config.includes("GALLERY_CLOUD_ENABLED=false"),"Cloud gallery must stay disabled without deployed storage rules");
console.log("PASS: regras versionadas com isolamento por UID, eventos imutáveis, fallback deny e galeria cloud desativada (sem validar produção).");
