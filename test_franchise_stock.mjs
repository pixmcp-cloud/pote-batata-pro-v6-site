import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {buildFranchiseCatalog,mergeFranchiseCatalog} from "./franchise_catalog.mjs";
import {initializeFranchiseStarterStock,shoppingNeeds,formatStockQuantity,FRANCHISE_STARTER_VERSION} from "./franchise_stock_core.mjs";
import vm from "node:vm";
const source=readFileSync("source/pote_app_base.html","utf8");
const matrix=JSON.parse(source.match(/<script id="backup" type="application\/json">([\s\S]*?)<\/script>/)[1]);
const catalog=buildFranchiseCatalog({data:matrix});
const env={window:{},console};vm.createContext(env);
vm.runInContext(readFileSync("beverage_catalog.js","utf8"),env);
const state={data:{brand:{name:"Test"},businessType:"batataria",settings:{usePackagingStock:true},
  ingredients:[],recipes:[],beverages:[],combos:[],orders:[],stockMovements:[],purchases:[]}};
mergeFranchiseCatalog(state,catalog);
const loaded=env.window.POTE_DRINKS.ensure(state);
assert.equal(loaded.beveragesAdded,11);
const result=initializeFranchiseStarterStock(state);
assert(result.changed);
assert.equal(result.ingredientsUpdated,41,"Todos os ingredientes das fichas oficiais devem ter saldo");
assert.equal(result.beveragesUpdated,11,"Todas as onze bebidas devem iniciar com dez unidades");
assert.equal(result.recipes,26);
assert.equal(state.data.franchiseStarterStockVersion,FRANCHISE_STARTER_VERSION);
assert(state.data.ingredients.every(i=>i.stock>0&&i.purchasePrice===0&&i.price===0),
  "Estoque inicial não deve inventar preço ou compras");
assert(state.data.beverages.every(b=>b.stock===10&&b.purchasePrice===0));
assert.equal(shoppingNeeds(state.data).length,0,"Lista de compras começa vazia com o estoque inicial completo");
const batata=state.data.ingredients.find(i=>i.id==="fr-batata");
const expected=state.data.recipes.reduce((sum,r)=>sum+(r.items.find(x=>x.id===batata.id)?.g||0)*5/(batata.yield/100),0);
assert(Math.abs(batata.stock-expected)<.01,"Rendimento de batata deve refletir cinco unidades de CADA sabor");
assert.equal(batata.yield,83,"Rendimento técnico da matriz deve ser respeitado");
const original=batata.stock,history=state.data.stockMovements.length;
assert.equal(initializeFranchiseStarterStock(state).changed,false);
assert.equal(batata.stock,original,"A inicialização não pode reabastecer após vendas");
batata.stock-=250;
const low=shoppingNeeds(state.data).find(x=>x.id==="fr-batata");
assert(low&&low.kind==="ingredient"&&low.level==="low");
assert(Math.abs(low.missing-250)<.01);
const bebida=state.data.beverages[0];
bebida.stock=4;
const drink=shoppingNeeds(state.data).find(x=>x.id===bebida.id);
assert.equal(drink.missing,6);
assert.equal(drink.unit,"un");
assert.equal(formatStockQuantity(drink.missing,drink.unit),"6 un");
state.data.orders.push({id:"pendente",status:"recebido",stockDeducted:false,qty:2,
 items:[{id:batata.id,g:205,yieldPct:83}],
 beverageItems:[{id:bebida.id,qty:1}]});
const reserved=shoppingNeeds(state.data).find(x=>x.id===batata.id);
assert(reserved.missing>low.missing,"Reservas precisam aumentar a reposição");
assert.equal(shoppingNeeds(state.data).find(x=>x.id===bebida.id).missing,8);
state.data.orders[0].stockDeducted=true;
assert.equal(shoppingNeeds(state.data).find(x=>x.id===bebida.id).missing,6,"Pedidos produzidos não podem reservar novamente");
assert.equal(state.data.stockMovements.length,history,"Saldo inicial não é compra real");
assert.equal(initializeFranchiseStarterStock(state).changed,false,"Sincronização posterior não recria bebidas ou insumos");
const next=structuredClone(catalog);
next.recipes.push({id:"r-novo",name:"Lanche Novo",items:[{id:"batata",g:300}],steps:[]});
mergeFranchiseCatalog(state,next);
assert.equal(initializeFranchiseStarterStock(state).changed,false);
const afterLaunch=shoppingNeeds(state.data).find(x=>x.id===batata.id);
assert(afterLaunch.missing>reserved.missing,"Novo sabor precisa entrar na lista sem crédito automático de estoque");
console.log("PASS: 41 insumos para cinco de cada sabor, 11 bebidas com 10 un, rendimento, reservas, reposição e inicialização única.");
