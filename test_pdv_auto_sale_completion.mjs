import assert from "node:assert/strict";
import {openCash,closeCash,calculateCash,paymentConfirmed,confirmPaymentOnSaleCompletion,activeSession} from "./pdv_cash_core.mjs";
import {summarizePdvReceipts} from "./pdv_cash_summary.mjs";
const order=(id,method,qty=1,price=20,session=null)=>({id,name:"Frango Cremoso",qty,price,
 cashSessionId:session,paymentMethod:method,paymentStatus:method==="Dinheiro"?"Pago em dinheiro":"Informado",
 status:"entregue",createdAt:"2026-11-18T09:00:00Z"});
const data={orders:[],cashSessions:[],cashMovements:[]};
data.orders.push(order("pix-1","Pix",1,20.9));
let r=confirmPaymentOnSaleCompletion(data,{orderId:"pix-1",operator:"Teste",at:"2026-11-18T09:05:00Z"});
assert.equal(r.recorded,true);
assert.equal(r.late,false);
assert.equal(data.orders[0].paymentStatus,"pago");
assert.equal(data.orders[0].cashSessionId,activeSession(data).id);
assert.equal(activeSession(data).openingCash,0,"First sale auto-opens a zero-float cash session without prompting");
assert.equal(activeSession(data).autoStarted,true);
assert.equal(data.orders[0].paymentConfirmationSource,"conclusao-venda");
assert.equal(data.orders[0].paymentConfirmedAt,"2026-11-18T09:05:00Z");
assert.equal(calculateCash(data,activeSession(data).id).confirmedByMethod.pix,20.9);
assert.equal(calculateCash(data,activeSession(data).id).pending,0);
assert.equal(data.cashMovements.length,0,"No duplicate cash-movement from confirming a sale");
assert.equal(confirmPaymentOnSaleCompletion(data,{orderId:"pix-1"}).recorded,false);
assert.equal(data.cashSessions.length,1);
data.orders.push(order("card-1","Cartão",2,40));
data.orders.push(order("cash-1","Dinheiro",1,50));
data.orders.push(order("delivery-1","Na entrega",1,30,activeSession(data).id));
data.orders.push({...order("not-done","Pix"),status:"em_producao"});
r=confirmPaymentOnSaleCompletion(data,{orderId:"card-1",at:"2026-11-18T09:06:00Z"});
assert(r.recorded);
assert.equal(confirmPaymentOnSaleCompletion(data,{orderId:"cash-1"}).recorded,true,"Cash was already paid but must be linked to the active shift");
assert.equal(data.orders.find(x=>x.id==="cash-1").cashSessionId,activeSession(data).id);
assert.equal(data.orders.find(x=>x.id==="cash-1").paymentConfirmationSource,"conclusao-venda");
assert.equal(confirmPaymentOnSaleCompletion(data,{orderId:"cash-1"}).recorded,false,"No duplicate cash payment");
assert.equal(confirmPaymentOnSaleCompletion(data,{orderId:"delivery-1"}).recorded,false);
assert.equal(paymentConfirmed(data.orders.find(x=>x.id==="delivery-1")),false);
assert.throws(()=>confirmPaymentOnSaleCompletion(data,{orderId:"not-done"}),/concluída/);
let summary=calculateCash(data,activeSession(data).id);
assert.equal(summary.confirmedByMethod.pix,20.9);
assert.equal(summary.confirmedByMethod.card,80);
assert.equal(summary.confirmedByMethod.cash,50);
assert.equal(summary.pending,30,"Na entrega stays pending");
assert.equal(summary.expectedCash,50,"Card+Pix never enter cash drawer");
let receipts=summarizePdvReceipts(summary);
assert.equal(receipts.gross,150.9);
assert.equal(receipts.pending,30);
const firstId=activeSession(data).id;
const frozen=closeCash(data,{countedCash:50,at:"2026-11-18T12:00:00Z"}).closedSummary;
assert.equal(frozen.confirmedByMethod.pix,20.9);
data.orders.push(order("late-pix","Pix",1,14.5,firstId));
r=confirmPaymentOnSaleCompletion(data,{orderId:"late-pix",at:"2026-11-18T13:00:00Z"});
assert.equal(r.recorded,true);
assert.equal(r.late,true);
assert.notEqual(r.sessionId,firstId);
assert.equal(data.cashMovements.filter(m=>m.kind==="late_payment").length,1);
assert.equal(confirmPaymentOnSaleCompletion(data,{orderId:"late-pix"}).recorded,false);
assert.equal(data.cashMovements.filter(m=>m.kind==="late_payment").length,1);
assert.deepEqual(calculateCash(data,firstId),frozen,"Closed shift is immutable");
assert.equal(summarizePdvReceipts(calculateCash(data,r.sessionId)).pix,14.5,"Late Pix belongs to new shift");
assert.equal(calculateCash(data,r.sessionId).expectedCash,0);
console.log("PASS: Concluir venda automatically records Pix, card and cash, prevents duplicate, auto-opens zero-float shift, preserves closed shifts and keeps payment on delivery pending.");
