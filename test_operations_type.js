const fs=require("node:fs");
const assert=require("node:assert/strict");
const css=fs.readFileSync("visual_refresh.css","utf8");
const html=fs.readFileSync("public/index.html","utf8");
const marker="/* Legibilidade corrigida: contorno preto nítido sem letras comprimidas. */";
assert(css.includes(marker),"Estilo final da tipografia não está presente");
const final=css.slice(css.lastIndexOf(marker));
assert(final.includes(".ops-grid .ops-card strong{"),"Regra final de títulos ausente");
assert(final.includes("font-weight:800!important"),"Peso excessivo da fonte pode juntar letras");
assert(final.includes("letter-spacing:0!important"),"Letras não devem ficar comprimidas");
assert(final.includes("font-size:clamp(22px,2.3vw,29px)!important"),"Escala desktop deve ser equilibrada");
assert(final.includes("font-size:clamp(19px,5.8vw,24px)!important"),"Escala mobile deve caber nos cards");
assert(final.includes("-webkit-text-stroke:1.7px #000!important"),"O contorno deve ser PRETO puro");
assert(final.includes("-webkit-text-fill-color:#fff!important"),"Preenchimento deve ser branco");
assert(final.includes("text-shadow:"),"Sombras pretas devem reforçar o contorno");
assert(final.includes("paint-order:stroke fill"),"O traçado preto deve ficar atrás do preenchimento branco");
assert(html.includes("visual_refresh.css?v=outline-readable-20261115"),"É necessário invalidar o cache do navegador");
console.log("PASS: letras separadas, tamanho responsivo, contorno preto e atualização de cache.");
