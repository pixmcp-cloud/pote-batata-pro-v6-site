const fs=require('node:fs');
const assert=require('node:assert/strict');
const css=fs.readFileSync('visual_refresh.css','utf8');
const source=fs.readFileSync('source/pote_app_base.html','utf8');
const html=fs.readFileSync('public/index.html','utf8');
const marker='/* Central: texto no MEIO do botão, letras mais espaçadas e contorno preto real em camada separada. */';
assert(css.includes(marker),'CSS de centralização não foi encontrado');
const final=css.slice(css.lastIndexOf(marker));
assert(final.includes('justify-content:center!important'),'Falta centralização vertical');
assert(final.includes('align-items:center!important'),'Falta centralização horizontal');
assert(final.includes('text-align:center!important'),'Falta alinhamento central');
assert(final.includes('letter-spacing:.035em!important'),'Letras precisam de espaçamento leve');
assert(final.includes('color:#ffffff!important'),'Texto deve permanecer branco');
assert(final.includes('strong::before'),'Camada preta independente ausente');
assert(final.includes('content:attr(data-outline)'),'Contorno deve repetir o texto do botão');
assert(final.includes('-webkit-text-stroke:5px #000!important'),'Camada externa deve ter contorno preto puro');
assert(final.includes('font-size:clamp(19px,5.35vw,23px)!important'),'Texto precisa caber no celular');
assert(source.includes('<strong data-outline="${label}">${label}</strong>'),'Botões precisam fornecer o texto para o contorno');
assert(html.includes('visual_refresh.css?v=centered-black-outline-20261115'),'Cache da nova versão não foi atualizado');
console.log('PASS: nomes centralizados, leve espaçamento e contorno preto duplicado.');
